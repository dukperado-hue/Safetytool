const ICON = { cut: '■', open: '▲', inconclusive: '?' };

export const esc = (s) => String(s == null ? '' : s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const nm = (m, id) => {
  const n = [m.hazard, m.topEvent, ...m.threats, ...m.consequences].find((x) => x && x.id === id);
  return n ? n.text : id;
};
const badge = (L, r) => `<span class="rb rb-${r}">${ICON[r]} ${esc(L.result[r])}</span>`;
const table = (head, rows) => `<table><thead><tr>${head.map((h) => `<th>${esc(h)}</th>`).join('')}</tr></thead><tbody>${rows.map((r) => `<tr>${r.map((c) => `<td>${c}</td>`).join('')}</tr>`).join('')}</tbody></table>`;

/**
 * opts: { lang, sections: string[], svg: string (diagram markup), asOf: 'YYYY-MM-DD', now: ISO string,
 *         baseline: model|null, ercFile: parsed erc-matrix.json|null }
 */
export function buildReport(m, opts = {}) {
  const L = T[opts.lang] || T.th;
  const want = new Set(opts.sections || SECTIONS);
  const asOf = opts.asOf || new Date().toISOString().slice(0, 10);
  const sim = m.threats.length && m.consequences.length ? simulateBowtie(m, { now: opts.now }) : { ok: false, errors: ['needs a threat and a consequence'] };
  const out = [];
  const h = (k) => `<h2>${esc(L.s[k])}</h2>`;

  out.push(`<header class="rh"><h1>${esc(L.doc)}</h1><p>${esc((m.meta && m.meta.title) || m.hazard.text || '')}</p><p class="rm">${esc(L.sub)}</p></header>`);
  out.push(`<div class="rn"><strong>${esc(L.notice)}</strong> ${esc(L.noticeBody)}</div>`);

  if (want.has('summary')) {
    const rows = [[esc(L.title), esc((m.meta && m.meta.title) || '')], [esc(L.hazard), esc(m.hazard.text)], [esc(L.top), esc(m.topEvent.text)], [esc(L.date), esc(asOf)]];
    if (sim.ok) {
      const s = sim.run.summary;
      rows.push([esc(L.run), `<code>${esc(sim.run.id)}</code>`], [esc(L.fp), `<code>${esc(sim.run.inputFingerprint)}</code>`],
        [esc(L.total), `${s.total} · ${badge(L, 'cut')} ${s.cut} · ${badge(L, 'open')} ${s.open} · ${badge(L, 'inconclusive')} ${s.inconclusive}`],
        [esc(L.reachLabel), esc(L.reach[sim.run.topEvent.reach])], [esc(L.fragile), String(s.fragileCuts)]);
    }
    out.push(`<section>${h('summary')}${table(['', ''], rows).replace('<thead><tr><th></th><th></th></tr></thead>', '')}</section>`);
  }
  if (want.has('diagram') && opts.svg) out.push(`<section class="fig">${h('diagram')}${opts.svg}</section>`);

  if (want.has('paths')) {
    if (!sim.ok) out.push(`<section>${h('paths')}<p>${esc((sim.errors || []).slice(0, 3).join('; '))}</p></section>`);
    else {
      const rows = sim.run.paths.map((p) => [esc(nm(m, p.threatId)), esc(nm(m, p.consequenceId)), badge(L, p.result) + (p.fragileCut ? ' *' : ''), esc(localizeMsg(p.reason || '', opts.lang))]);
      let html = `<section>${h('paths')}${table([L.threat, L.cons, L.res, L.why], rows)}`;
      if (sim.run.uncontrolledEscalations.length) html += `<h3>${esc(L.unctl)}</h3><ul>${sim.run.uncontrolledEscalations.map((u) => `<li>${esc(u.text)}</li>`).join('')}</ul>`;
      out.push(html + '</section>');
    }
  }

  if (want.has('barriers')) {
    const reg = assuranceRegister(m, asOf);
    const rows = reg.map((r) => [`<code>${esc(r.controlId)}</code>`, esc(r.text), esc(L[r.side === 'prevent' ? 'prevent' : 'recover']), esc(L.st[r.status] || r.status) + (r.critical ? ` · ${esc(L.crit)}` : ''), esc(r.owner), esc(r.gaps.join(', ') || L.noGaps)]);
    out.push(`<section>${h('barriers')}${rows.length ? table([L.bid, L.btext, L.side, L.status, L.owner, L.gaps], rows) : `<p>${esc(L.none)}</p>`}</section>`);
  }

  if (want.has('erc')) {
    const e = m.erc || {};
    const mx = opts.ercFile ? pickMatrix(opts.ercFile, e.matrix || null) : null;
    const hit = mx && e.outcome && e.barriers ? ercLookup(mx, e.outcome, e.barriers) : null;
    let html = `<section>${h('erc')}`;
    if (!e.outcome || !e.barriers) html += `<p>${esc(L.ercNone)}</p>`;
    else {
      const rows = [[esc(L.ercOutcome), esc(hit ? hit.outcome : e.outcome)], [esc(L.ercBarrier), esc(e.barriers)]];
      if (hit) rows.push([esc(L.ercScore), `<strong>${esc(hit.score)}</strong> (${esc(hit.band)})`]);
      html += table(['', ''], rows).replace('<thead><tr><th></th><th></th></tr></thead>', '');
      if (e.rationale) html += `<p><strong>${esc(L.ercWhy)}:</strong> ${esc(e.rationale)}</p>`;
    }
    out.push(html + `<p class="rm">${esc(L.ercNote)}</p></section>`);
  }

  if (want.has('evidence')) {
    const ev = (m.evidence || []).map((x) => [`<code>${esc(x.id)}</code>`, esc(x.kind), esc(x.source || ''), esc([x.reference, x.limitation].filter(Boolean).join(' · '))]);
    const as = (m.assumptions || []).map((x) => [`<code>${esc(x.id)}</code>`, esc(x.statement)]);
    out.push(`<section>${h('evidence')}<h3>${esc(L.evid)}</h3>${ev.length ? table([L.bid, L.kind, L.src, L.refLim], ev) : `<p>${esc(L.none)}</p>`}<h3>${esc(L.assum)}</h3>${as.length ? table([L.bid, ''], as) : `<p>${esc(L.none)}</p>`}</section>`);
  }

  if (want.has('compare') && opts.baseline) {
    const r = compareBowties(opts.baseline, m);
    if (r.ok) {
      const d = r.diff;
      const rows = [[esc(L.cmpBase), d.pathCount.baseline.cut, d.pathCount.baseline.open, d.pathCount.baseline.inconclusive], ['', d.pathCount.alternative.cut, d.pathCount.alternative.open, d.pathCount.alternative.inconclusive]];
      out.push(`<section>${h('compare')}<p>${esc(L.cmpNote)}</p>${table(['', L.result.cut, L.result.open, L.result.inconclusive], rows)}<p>${esc(L.newlyCut)}: ${d.newlyCut.length} · ${esc(L.newlyOpen)}: ${d.newlyOpen.length}</p>${d.notes.length ? `<ul>${d.notes.map((n) => `<li>${esc(localizeMsg(n, opts.lang))}</li>`).join('')}</ul>` : ''}</section>`);
    }
  }

  if (want.has('limits') && sim.ok) out.push(`<section>${h('limits')}<ul>${sim.run.limitations.map((x) => `<li>${esc(localizeMsg(x, opts.lang))}</li>`).join('')}</ul></section>`);
  out.push(`<footer class="rf">${esc(L.disclaimer)}</footer>`);
  return `<article class="rpt">${out.join('\n')}</article>`;
}

